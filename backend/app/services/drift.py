def _run_terraform(args: list[str], cwd: str, timeout: int = 120) -> tuple[str, str, int]:
    """Run a terraform command and return stdout, stderr, returncode.

    This is the synchronous version kept for backward compatibility.
    """
    result = subprocess.run(
        ["terraform"] + args,
        cwd=cwd,
        capture_output=True,
        text=True,
        timeout=timeout,
        env=_terraform_env(),
    )
    # Strip ANSI escape codes
    ansi_escape = re.compile(r"\x1B(?:[@-Z\\-_]|\[[0-?]*[ -/]*[@-~])")
    stdout = ansi_escape.sub("", result.stdout)
    stderr = ansi_escape.sub("", result.stderr)
    return stdout, stderr, result.returncode


async def _run_terraform_streaming(
    args: list[str],
    cwd: str,
    job_id: str,
    phase: str,
    timeout: int = 120,
) -> tuple[str, str, int]:
    """Run a terraform command with real-time line-by-line streaming.

    Streams each line of stdout/stderr to WebSocket subscribers.
    Returns the same tuple as _run_terraform for compatibility.
    """
    stdout_lines: list[str] = []
    stderr_lines: list[str] = []

    try:
        process = await asyncio.create_subprocess_exec(
            "terraform",
            *args,
            cwd=cwd,
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE,
            env=_terraform_env(),
        )

        async def read_stream(stream: asyncio.StreamReader, stream_name: str, buffer: list[str]):
            """Read a stream line by line and emit to subscribers."""
            while True:
                line_bytes = await stream.readline()
                if not line_bytes:
                    break
                line = line_bytes.decode("utf-8", errors="replace").rstrip("\n")
                sanitized = _sanitize_line(line, cwd)
                buffer.append(sanitized)
                _emit_log(job_id, sanitized, stream_name, phase)

        # Read stdout and stderr concurrently
        await asyncio.wait_for(
            asyncio.gather(
                read_stream(process.stdout, "stdout", stdout_lines),
                read_stream(process.stderr, "stderr", stderr_lines),
            ),
            timeout=timeout,
        )

        await process.wait()
        returncode = process.returncode

    except asyncio.TimeoutError:
        # Kill the process on timeout
        try:
            process.kill()
            await process.wait()
        except ProcessLookupError:
            pass
        _emit_log(job_id, f"[ERROR] Command timed out after {timeout}s", "stderr", phase)
        stderr_lines.append(f"Command timed out after {timeout}s")
        returncode = -1

    except Exception as e:
        _emit_log(job_id, f"[ERROR] {str(e)}", "stderr", phase)
        stderr_lines.append(str(e))
        returncode = -1

    # Strip ANSI from the collected output (for parsing, not for streaming)
    ansi_escape = re.compile(r"\x1B(?:[@-Z\\-_]|\[[0-?]*[ -/]*[@-~])")
    stdout = ansi_escape.sub("", "\n".join(stdout_lines))
    stderr = ansi_escape.sub("", "\n".join(stderr_lines))

    return stdout, stderr, returncode


def _parse_plan_output(stdout: str, stderr: str) -> DriftResult:
    """Parse terraform plan output to detect drift or errors that need fixing.

    Note: 'resources to add' without changes/destroys is NOT drift — it means
    the import didn't work or resources are missing from state. Only changes
    and destroys represent actual drift.
    """
    combined = stdout + "\n" + stderr
    no_changes = "No changes. Your infrastructure matches the configuration" in combined

    # Count from individual resource lines
    changed = len(re.findall(r"# .+ will be updated", combined))
    added = len(re.findall(r"# .+ will be created", combined))
    destroyed = len(re.findall(r"# .+ will be destroyed", combined))
    replaced = len(re.findall(r"# .+ must be replaced", combined))

    # Also parse the summary line: "Plan: X to add, Y to change, Z to destroy."
    plan_summary = re.search(r"Plan:\s*(\d+)\s*to add,\s*(\d+)\s*to change,\s*(\d+)\s*to destroy", combined)
    if plan_summary:
        summary_added = int(plan_summary.group(1))
        summary_changed = int(plan_summary.group(2))
        summary_destroyed = int(plan_summary.group(3))
        # Use the max of regex matches and summary (summary is more reliable)
        added = max(added, summary_added)
        changed = max(changed, summary_changed)
        destroyed = max(destroyed, summary_destroyed)

    # Count replacements as both change and destroy
    changed += replaced

    # Detect validation/structural errors that AI can fix
    has_errors = bool(re.search(r"Error:", combined))

    # Real drift = changes to existing resources, replacements, destroys, or errors
    # 'to add' alone is NOT drift — it means import is missing
    has_real_drift = changed > 0 or destroyed > 0 or has_errors

    return DriftResult(
        has_drift=not no_changes and has_real_drift,
        plan_output=combined,
        resources_changed=changed,
        resources_added=added,
        resources_destroyed=destroyed,
    )


def get_drift_job_status(job_id: str) -> dict | None:
    """Get drift job status."""
    return _drift_jobs.get(job_id)


def cancel_drift_job(job_id: str) -> bool:
    """Cancel a running drift job.

    Sets a cancellation flag that the run loop checks between steps.
    Returns True if the job was found and cancellation requested.
    """
    job = _drift_jobs.get(job_id)
    if not job:
        return False
    if job["status"] != "running":
        return False
    job["cancel_requested"] = True
    return True


async def start_drift_detection(
    tf_files: dict[str, str],
    bucket: str,
    prefix: str,
    project_id: str,
) -> str:
    """Start a drift detection and auto-fix job.

    Args:
        tf_files: Dict of filename → HCL content (the generated terraform files).
        bucket: GCS bucket for remote state.
        prefix: State prefix in the bucket.
        project_id: GCP project ID.

    Returns:
        Job ID for tracking progress.
    """
    job_id = str(uuid.uuid4())
    _drift_jobs[job_id] = {
        "status": "running",
        "phase": "init",
        "progress": {"iteration": 0, "max_iterations": MAX_FIX_ITERATIONS, "message": "Initializing..."},
        "started_at": time.time(),
        "result": None,
        "error": None,
        "fix_history": [],
    }

    asyncio.create_task(_run_drift_detection(job_id, tf_files, bucket, prefix, project_id))
    return job_id


async def _run_drift_detection(
    job_id: str,
    tf_files: dict[str, str],
    bucket: str,
    prefix: str,
    project_id: str,
) -> None:
    """Execute drift detection and auto-fix loop with real-time streaming."""
    job = _drift_jobs[job_id]

    # Get AI config
    ai_config = get_active_config()
    if not ai_config:
        job["status"] = "failed"
        job["error"] = "No AI provider configured. Configure one in Settings."
        _emit_complete(job_id, "failed", "No AI provider configured.")
        return

    # Create temp directory with terraform files
    work_dir = tempfile.mkdtemp(prefix="terramorph-drift-")

    try:
        # Write all terraform files (skip provider.tf and backend.tf — we generate our own)
        for filename, content in tf_files.items():
            if filename in ("provider.tf", "backend.tf"):
                continue
            filepath = os.path.join(work_dir, filename)
            with open(filepath, "w") as f:
                f.write(content)

        # Write backend.tf
        backend_content = f'''terraform {{
  backend "gcs" {{
    bucket = "{bucket}"
    prefix = "{prefix}"
  }}
}}
'''
        with open(os.path.join(work_dir, "backend.tf"), "w") as f:
            f.write(backend_content)

        # Write provider.tf — always overwrite to ensure correct provider versions
        # User-supplied provider.tf may have outdated versions that miss newer resources
        provider_content = f'''terraform {{
  required_version = ">= 1.5.0"
  required_providers {{
    google = {{
      source  = "hashicorp/google"
      version = ">= 6.0"
    }}
    google-beta = {{
      source  = "hashicorp/google-beta"
      version = ">= 6.0"
    }}
  }}
}}

provider "google" {{
  project = "{project_id}"
}}

provider "google-beta" {{
  project = "{project_id}"
}}
'''
        with open(os.path.join(work_dir, "provider.tf"), "w") as f:
            f.write(provider_content)

        # Step 1: terraform init
        job["phase"] = "init"
        job["progress"]["message"] = "Running terraform init..."
        _emit_phase(job_id, "init", "Running terraform init...")

        stdout, stderr, rc = await _run_terraform_streaming(
            ["init", "-no-color"], work_dir, job_id, "init", timeout=180
        )
        if rc != 0:
            job["status"] = "failed"
            job["error"] = f"terraform init failed: {stderr}"
            _emit_complete(job_id, "failed", f"terraform init failed")
            return

        # Check cancellation
        if job.get("cancel_requested"):
            job["status"] = "cancelled"
            job["phase"] = "done"
            _emit_log(job_id, "⚠ Process cancelled by user.", "stderr", "init")
            _emit_complete(job_id, "cancelled", "Process cancelled by user.")
            return

        # Step 2: Initial plan — check for HCL errors
        job["phase"] = "plan"
        job["progress"]["message"] = "Running initial terraform plan..."
        _emit_phase(job_id, "plan", "Running initial terraform plan...")

        stdout, stderr, rc = await _run_terraform_streaming(
            ["plan", "-no-color", "-lock=false"], work_dir, job_id, "plan"
        )

        # Check for fatal errors that AI cannot fix
        combined_output = stdout + "\n" + stderr
        fatal_error = _detect_fatal_error(combined_output, rc)
        if fatal_error:
            job["status"] = "failed"
            job["phase"] = "done"
            job["error"] = fatal_error
            _emit_log(job_id, f"[FATAL] {fatal_error}", "stderr", "plan")
            _emit_complete(job_id, "failed", fatal_error)
            return

        # Step 2b: If plan has HCL/validation errors (rc != 0), fix them with AI first
        if rc != 0:
            _emit_log(job_id, "▶ Plan has validation errors, attempting AI fix...", "stdout", "fix")
            for err_iteration in range(1, MAX_FIX_ITERATIONS + 1):
                if job.get("cancel_requested"):
                    job["status"] = "cancelled"
                    job["phase"] = "done"
                    _emit_log(job_id, "⚠ Process cancelled by user.", "stderr", "fix")
                    _emit_complete(job_id, "cancelled", "Process cancelled by user.")
                    return

                job["phase"] = "fix"
                job["progress"]["iteration"] = err_iteration
                job["progress"]["message"] = f"Fixing errors (attempt {err_iteration}/{MAX_FIX_ITERATIONS})..."
                _emit_phase(job_id, "fix", f"AI fixing errors (attempt {err_iteration}/{MAX_FIX_ITERATIONS})...")

                # Get resource files for AI
                resource_files = {
                    f: open(os.path.join(work_dir, f)).read()
                    for f in os.listdir(work_dir)
                    if f.endswith(".tf") and f not in ("provider.tf", "backend.tf", "import.tf")
                }
                all_tf_content = "\n\n".join(
                    f"# --- {fname} ---\n{content}" for fname, content in resource_files.items()
                )

                plan_output_for_ai = (stdout + "\n" + stderr)[-4000:]
                prompt = FIX_DRIFT_PROMPT.format(tf_content=all_tf_content, plan_output=plan_output_for_ai)
                _emit_log(job_id, "▶ Sending code to AI for error resolution...", "stdout", "fix")

                try:
                    from app.services.ai_cleaner import call_ai
                    fixed_content = await call_ai(
                        prompt=prompt,
                        provider=ai_config.provider,
                        api_key=ai_config.api_key,
                        model=ai_config.model or None,
                        endpoint_url=ai_config.endpoint_url or None,
                    )
                except Exception as e:
                    _emit_log(job_id, f"[ERROR] AI fix failed: {str(e)}", "stderr", "fix")
                    if err_iteration == MAX_FIX_ITERATIONS:
                        job["status"] = "failed"
                        job["error"] = f"AI could not fix validation errors after {err_iteration} attempts."
                        _emit_complete(job_id, "failed", job["error"])
                        return
                    continue

                # Validate and apply AI response
                if not fixed_content or not fixed_content.strip():
                    _emit_log(job_id, "[WARN] AI returned empty response, retrying...", "stderr", "fix")
                    continue
                fixed_content = _strip_markdown_fences(fixed_content)
                if not re.search(r'\b(resource|data|module|variable|output|locals)\s+"', fixed_content):
                    _emit_log(job_id, "[WARN] AI response doesn't look like valid HCL, retrying...", "stderr", "fix")
                    continue

                _emit_log(job_id, f"✓ AI returned fixed code ({len(fixed_content)} chars), applying...", "stdout", "fix")
                _write_fixed_content(work_dir, fixed_content, resource_files)

                # Re-run plan to check if errors are resolved
                _emit_phase(job_id, "plan", f"Verifying error fix (attempt {err_iteration}/{MAX_FIX_ITERATIONS})...")
                stdout, stderr, rc = await _run_terraform_streaming(
                    ["plan", "-no-color", "-lock=false"], work_dir, job_id, "plan"
                )

                if rc == 0:
                    _emit_log(job_id, "✓ Validation errors resolved!", "stdout", "fix")
                    break

                # Check if the remaining error is still fixable
                combined_output = stdout + "\n" + stderr
                fatal_error = _detect_fatal_error(combined_output, rc)
                if fatal_error:
                    job["status"] = "failed"
                    job["phase"] = "done"
                    job["error"] = fatal_error
                    _emit_complete(job_id, "failed", fatal_error)
                    return
            else:
                # Exhausted error-fix retries
                job["status"] = "failed"
                job["error"] = "Could not resolve validation errors after maximum attempts."
                _emit_complete(job_id, "failed", job["error"])
                return

        # Check cancellation before import
        if job.get("cancel_requested"):
            job["status"] = "cancelled"
            job["phase"] = "done"
            _emit_log(job_id, "⚠ Process cancelled by user.", "stderr", "import")
            _emit_complete(job_id, "cancelled", "Process cancelled by user.")
            return

        # Step 3: Import — apply import blocks to bring resources into state
        has_import_file = os.path.exists(os.path.join(work_dir, "import.tf"))
        if has_import_file:
            job["phase"] = "import"
            job["progress"]["message"] = "Importing resources into state..."
            _emit_phase(job_id, "import", "Importing resources into state (terraform apply)...")

            stdout, stderr, rc = await _run_terraform_streaming(
                ["apply", "-auto-approve", "-no-color", "-lock=false"], work_dir, job_id, "import", timeout=300
            )

            if rc != 0:
                # Import failures are not always fatal — some resources may already be in state
                if "Cannot import non-existent remote object" in (stdout + stderr):
                    _emit_log(job_id, "[WARN] Some resources could not be imported (may not exist). Continuing...", "stderr", "import")
                elif "Resource already managed by Terraform" in (stdout + stderr):
                    _emit_log(job_id, "✓ Resources already in state, skipping import.", "stdout", "import")
                else:
                    _emit_log(job_id, f"[WARN] Import had issues (rc={rc}), continuing to plan...", "stderr", "import")

            # Remove import.tf after apply — import blocks are one-time use
            import_path = os.path.join(work_dir, "import.tf")
            if os.path.exists(import_path):
                os.remove(import_path)
                _emit_log(job_id, "✓ Import blocks applied, removed import.tf", "stdout", "import")
        else:
            _emit_log(job_id, "ℹ No import.tf found, skipping import step.", "stdout", "plan")

        # Check cancellation before drift fix
        if job.get("cancel_requested"):
            job["status"] = "cancelled"
            job["phase"] = "done"
            _emit_log(job_id, "⚠ Process cancelled by user.", "stderr", "verify")
            _emit_complete(job_id, "cancelled", "Process cancelled by user.")
            return

        # Step 4: Plan again — now with imported state, detect real drift
        job["phase"] = "verify"
        job["progress"]["message"] = "Running plan to detect drift..."
        _emit_phase(job_id, "verify", "Running plan after import to detect drift...")

        stdout, stderr, rc = await _run_terraform_streaming(
            ["plan", "-no-color", "-lock=false"], work_dir, job_id, "verify"
        )
        drift_result = _parse_plan_output(stdout, stderr)

        if not drift_result.has_drift:
            # Check if there are resources "to add" — means import didn't cover them
            if drift_result.resources_added > 0:
                job["status"] = "completed"
                job["phase"] = "done"
                job["result"] = {
                    "drift_detected": False,
                    "message": f"No drift detected, but {drift_result.resources_added} resource(s) are planned to be created. "
                               f"This means the import was successful for existing resources. "
                               f"Run 'terraform apply' to create any new resources defined in code.",
                    "iterations_needed": 0,
                    "final_files": _read_tf_files(work_dir),
                }
                _emit_log(job_id, f"✓ No drift. {drift_result.resources_added} resource(s) planned to add (not drift — run apply to create).", "stdout", "verify")
                _emit_complete(job_id, "completed", "No drift detected.")
                return

            job["status"] = "completed"
            job["phase"] = "done"
            job["result"] = {
                "drift_detected": False,
                "message": "No changes. Your infrastructure matches the configuration.",
                "iterations_needed": 0,
                "final_files": _read_tf_files(work_dir),
            }
            _emit_complete(job_id, "completed", "No drift detected.")
            return

        # Step 5: Iterative drift fix loop
        for iteration in range(1, MAX_FIX_ITERATIONS + 1):
            # Check cancellation before each iteration
            if job.get("cancel_requested"):
                job["status"] = "cancelled"
                job["phase"] = "done"
                _emit_log(job_id, "⚠ Process cancelled by user.", "stderr", "fix")
                _emit_complete(job_id, "cancelled", "Process cancelled by user.")
                return

            job["phase"] = "fix"
            job["progress"]["iteration"] = iteration
            job["progress"]["message"] = f"Fixing drift (attempt {iteration}/{MAX_FIX_ITERATIONS})..."
            _emit_phase(job_id, "fix", f"AI fixing drift (attempt {iteration}/{MAX_FIX_ITERATIONS})...")

            job["fix_history"].append({
                "iteration": iteration,
                "drift": {
                    "changed": drift_result.resources_changed,
                    "added": drift_result.resources_added,
                    "destroyed": drift_result.resources_destroyed,
                },
            })

            # Get all resource .tf files (skip provider.tf, backend.tf, import.tf)
            resource_files = {
                f: open(os.path.join(work_dir, f)).read()
                for f in os.listdir(work_dir)
                if f.endswith(".tf") and f not in ("provider.tf", "backend.tf", "import.tf")
            }

            # Concatenate all resource content for AI
            all_tf_content = "\n\n".join(
                f"# --- {fname} ---\n{content}" for fname, content in resource_files.items()
            )

            # Call AI to fix
            prompt = FIX_DRIFT_PROMPT.format(
                tf_content=all_tf_content,
                plan_output=drift_result.plan_output[-4000:],  # Limit plan output size
            )

            _emit_log(job_id, f"▶ Sending code to AI for analysis...", "stdout", "fix")

            try:
                from app.services.ai_cleaner import call_ai
                fixed_content = await call_ai(
                    prompt=prompt,
                    provider=ai_config.provider,
                    api_key=ai_config.api_key,
                    model=ai_config.model or None,
                    endpoint_url=ai_config.endpoint_url or None,
                )
            except Exception as e:
                logger.error(f"AI fix attempt {iteration} failed: {e}")
                _emit_log(job_id, f"[ERROR] AI fix failed: {str(e)}", "stderr", "fix")
                if iteration == MAX_FIX_ITERATIONS:
                    job["status"] = "failed"
                    job["error"] = f"AI fix failed after {iteration} attempts: {str(e)}"
                    _emit_complete(job_id, "failed", f"AI fix failed after {iteration} attempts")
                    return
                continue

            # Validate AI response before applying
            if not fixed_content or not fixed_content.strip():
                _emit_log(job_id, "[WARN] AI returned empty response, retrying...", "stderr", "fix")
                continue

            # Strip markdown fences if AI included them despite instructions
            fixed_content = _strip_markdown_fences(fixed_content)

            # Sanity check: response should contain at least one resource or data block
            if not re.search(r'\b(resource|data|module|variable|output|locals)\s+"', fixed_content):
                _emit_log(job_id, "[WARN] AI response doesn't look like valid HCL, retrying...", "stderr", "fix")
                logger.warning(f"AI returned non-HCL content (iteration {iteration}): {fixed_content[:200]}")
                continue

            # Check AI didn't introduce dangerous constructs
            if "provisioner" in fixed_content and "provisioner" not in all_tf_content:
                _emit_log(job_id, "[WARN] AI tried to add provisioner blocks, rejecting...", "stderr", "fix")
                continue

            if "lifecycle" in fixed_content and "ignore_changes" in fixed_content:
                if "ignore_changes" not in all_tf_content:
                    _emit_log(job_id, "[WARN] AI tried to add ignore_changes, rejecting...", "stderr", "fix")
                    continue

            _emit_log(job_id, f"✓ AI returned valid code ({len(fixed_content)} chars), applying...", "stdout", "fix")

            # Write fixed content back
            _write_fixed_content(work_dir, fixed_content, resource_files)

            # Re-run plan (verify phase)
            job["phase"] = "verify"
            job["progress"]["message"] = f"Verifying fix (attempt {iteration}/{MAX_FIX_ITERATIONS})..."
            _emit_phase(job_id, "verify", f"Verifying fix (attempt {iteration}/{MAX_FIX_ITERATIONS})...")

            stdout, stderr, rc = await _run_terraform_streaming(
                ["plan", "-no-color", "-lock=false"], work_dir, job_id, "verify"
            )
            drift_result = _parse_plan_output(stdout, stderr)

            if not drift_result.has_drift:
                # Success!
                job["status"] = "completed"
                job["phase"] = "done"
                job["result"] = {
                    "drift_detected": True,
                    "drift_fixed": True,
                    "message": f"Drift fixed successfully after {iteration} iteration(s).",
                    "iterations_needed": iteration,
                    "final_files": _read_tf_files(work_dir),
                }
                _emit_complete(job_id, "completed", f"Drift fixed after {iteration} iteration(s)!")
                return

        # Exhausted retries
        job["status"] = "completed"
        job["phase"] = "done"
        job["result"] = {
            "drift_detected": True,
            "drift_fixed": False,
            "message": f"Could not fully resolve drift after {MAX_FIX_ITERATIONS} attempts. Manual review needed.",
            "iterations_needed": MAX_FIX_ITERATIONS,
            "remaining_drift": drift_result.plan_output[-2000:],
            "final_files": _read_tf_files(work_dir),
        }
        _emit_complete(job_id, "completed", "Drift not fully resolved. Manual review needed.")

    except Exception as e:
        job["status"] = "failed"
        job["error"] = str(e)
        logger.error(f"Drift detection job {job_id} failed: {e}")
        _emit_complete(job_id, "failed", str(e))
    finally:
        # Cleanup temp directory
        shutil.rmtree(work_dir, ignore_errors=True)
        # Clean up subscribers after a delay (let clients receive final messages)
        await asyncio.sleep(2)
        if job_id in _drift_subscribers:
            del _drift_subscribers[job_id]


def _read_tf_files(work_dir: str) -> dict[str, str]:
    """Read all .tf files from work directory."""
    files = {}
    for f in os.listdir(work_dir):
        if f.endswith(".tf"):
            with open(os.path.join(work_dir, f)) as fh:
                files[f] = fh.read()
    return files


def _write_fixed_content(work_dir: str, fixed_content: str, resource_files: dict[str, str]) -> None:
    """Write AI-fixed content back to the work directory.

    If the AI preserved file markers (# --- filename.tf ---), split back into files.
    Otherwise, write to the first resource file.
    """
    if "# ---" in fixed_content:
        current_file = None
        current_lines: list[str] = []
        for line in fixed_content.split("\n"):
            marker_match = re.match(r"# --- (.+\.tf) ---", line)
            if marker_match:
                if current_file and current_lines:
                    with open(os.path.join(work_dir, current_file), "w") as f:
                        f.write("\n".join(current_lines))
                current_file = marker_match.group(1)
                current_lines = []
            else:
                current_lines.append(line)
        if current_file and current_lines:
            with open(os.path.join(work_dir, current_file), "w") as f:
                f.write("\n".join(current_lines))
    else:
        first_file = next(iter(resource_files.keys()), "main.tf")
        with open(os.path.join(work_dir, first_file), "w") as f:
            f.write(fixed_content)
