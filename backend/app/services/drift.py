# Pub/Sub for real-time log streaming
# ---------------------------------------------------------------------------


def subscribe(job_id: str) -> asyncio.Queue:
    """Subscribe to log events for a drift job. Returns a bounded queue."""
    if job_id not in _drift_subscribers:
        _drift_subscribers[job_id] = []

    if len(_drift_subscribers[job_id]) >= MAX_SUBSCRIBERS_PER_JOB:
        raise RuntimeError(f"Max subscribers ({MAX_SUBSCRIBERS_PER_JOB}) reached for job {job_id}")

    queue: asyncio.Queue = asyncio.Queue(maxsize=MAX_QUEUE_SIZE)
    _drift_subscribers[job_id].append(queue)
    return queue


def unsubscribe(job_id: str, queue: asyncio.Queue) -> None:
    """Unsubscribe from log events for a drift job."""
    if job_id in _drift_subscribers:
        try:
            _drift_subscribers[job_id].remove(queue)
        except ValueError:
            pass
        # Clean up empty subscriber lists
        if not _drift_subscribers[job_id]:
            del _drift_subscribers[job_id]


def _emit_log(job_id: str, line: str, stream: str, phase: str) -> None:
    """Emit a log line to all subscribers for a job (non-blocking)."""
    if job_id not in _drift_subscribers:
        return

    message = {
        "type": "log",
        "data": {
            "line": line,
            "stream": stream,
            "phase": phase,
            "timestamp": time.time(),
        },
    }

    for queue in _drift_subscribers.get(job_id, []):
        try:
            queue.put_nowait(message)
        except asyncio.QueueFull:
            # Drop oldest message to make room (ring buffer behavior)
            try:
                queue.get_nowait()
                queue.put_nowait(message)
            except (asyncio.QueueEmpty, asyncio.QueueFull):
                pass


def _emit_phase(job_id: str, phase: str, message: str) -> None:
    """Emit a phase change event to all subscribers."""
    if job_id not in _drift_subscribers:
        return

    event = {
        "type": "phase",
        "data": {
            "phase": phase,
            "message": message,
            "timestamp": time.time(),
        },
    }

    for queue in _drift_subscribers.get(job_id, []):
        try:
            queue.put_nowait(event)
        except asyncio.QueueFull:
            try:
                queue.get_nowait()
                queue.put_nowait(event)
            except (asyncio.QueueEmpty, asyncio.QueueFull):
                pass


def _emit_complete(job_id: str, status: str, message: str) -> None:
    """Emit a completion event to all subscribers."""
    if job_id not in _drift_subscribers:
        return

    event = {
        "type": "complete",
        "data": {
            "status": status,
            "message": message,
            "timestamp": time.time(),
        },
    }

    for queue in _drift_subscribers.get(job_id, []):
        try:
            queue.put_nowait(event)
        except asyncio.QueueFull:
            try:
                queue.get_nowait()
                queue.put_nowait(event)
            except (asyncio.QueueEmpty, asyncio.QueueFull):
                pass


# ---------------------------------------------------------------------------
# Sanitization
# ---------------------------------------------------------------------------


def _sanitize_line(line: str, work_dir: str) -> str:
    """Sanitize a log line before streaming to clients.

    - Replaces absolute temp directory paths with [WORKDIR]
    - Redacts potential credentials/tokens
    """
    # Replace temp dir path
    if work_dir:
        line = line.replace(work_dir, "[WORKDIR]")
        # Also handle paths that might have trailing slash variants
        line = line.replace(work_dir.rstrip("/"), "[WORKDIR]")

    # Redact credentials
    for pattern in _CREDENTIAL_PATTERNS:
        line = pattern.sub("[REDACTED]", line)

    return line


def _strip_markdown_fences(content: str) -> str:
    """Strip markdown code fences from AI response if present.

    AI models sometimes wrap output in ```hcl ... ``` despite instructions.
    """
    content = content.strip()
    # Remove opening fence (```hcl, ```terraform, ```)
    if content.startswith("```"):
        first_newline = content.find("\n")
        if first_newline != -1:
            content = content[first_newline + 1:]
    # Remove closing fence
    if content.rstrip().endswith("```"):
        content = content.rstrip()[:-3].rstrip()
    return content


def _detect_fatal_error(output: str, returncode: int) -> str | None:
    """Detect fatal Terraform errors that AI CANNOT fix.

    Only blocks errors that require human intervention or infrastructure changes.
    Errors that the AI CAN fix (wrong argument names, missing attributes,
    unsupported blocks, type mismatches) are allowed through to the fix loop.

    Returns an error message if truly fatal, or None to proceed with AI fix.
    """
    if returncode == 0:
        return None

    # Duplicate resource — structural issue, AI can't resolve without removing code
    if "Duplicate resource" in output:
        match = re.search(r'Duplicate resource "([^"]+)" "([^"]+)"', output)
        if match:
            return (
                f"Duplicate resource detected: {match.group(1)}.{match.group(2)}. "
                f"This is a code generation issue, not drift. "
                f"Please regenerate the Terraform code or manually remove the duplicate from the editor."
            )
        return "Duplicate resource detected in generated code. Remove duplicates before running drift detection."

    # Duplicate provider
    if "Duplicate provider configuration" in output:
        return "Duplicate provider configuration. Ensure provider.tf is not duplicated in the Terraform code."

    # Missing required provider / network issues
    if "Could not retrieve the list of available versions" in output or "Failed to query available provider packages" in output:
        return "Provider not available. Check internet connectivity and provider configuration."

    # Backend errors — can't proceed without state access
    if "Error configuring the backend" in output or "Error loading state" in output:
        return "Backend configuration error. Verify the GCS bucket exists and you have access permissions."

    # Auth errors — no credentials = nothing works
    if "google: could not find default credentials" in output or "oauth2: cannot fetch token" in output:
        return "GCP authentication error. Ensure Application Default Credentials are configured correctly."

    # Everything else (invalid arguments, unsupported blocks, wrong attribute names,
    # resource type issues, etc.) — let the AI try to fix it
    return None


