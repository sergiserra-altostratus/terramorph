# Terraform plugin cache directory — persists provider binaries between jobs
# Reduces terraform init from ~30-60s to ~2-3s on subsequent runs
PLUGIN_CACHE_DIR = os.environ.get("TF_PLUGIN_CACHE_DIR", "/app/data/.terraform-plugin-cache")

# Ensure cache directory exists (safe for environments where /app doesn't exist)
try:
    os.makedirs(PLUGIN_CACHE_DIR, exist_ok=True)
except OSError:
    # Fallback to temp dir if configured path is not writable
    PLUGIN_CACHE_DIR = os.path.join(tempfile.gettempdir(), "terramorph-plugin-cache")
    os.makedirs(PLUGIN_CACHE_DIR, exist_ok=True)

# Environment for terraform subprocesses (inherits current env + adds cache)
def _terraform_env() -> dict[str, str]:
    """Get environment variables for terraform subprocess with plugin cache."""
    env = os.environ.copy()
    env["TF_PLUGIN_CACHE_DIR"] = PLUGIN_CACHE_DIR
    return env

# In-memory drift job storage
_drift_jobs: dict[str, dict[str, Any]] = {}

# Pub/sub for real-time log streaming
_drift_subscribers: dict[str, list[asyncio.Queue]] = {}

# Limits
MAX_FIX_ITERATIONS = 10
MAX_SUBSCRIBERS_PER_JOB = 5
MAX_QUEUE_SIZE = 1000

# Patterns for credential redaction in streamed output
_CREDENTIAL_PATTERNS = [
    re.compile(r"(ya29\.[A-Za-z0-9_\-]{20,})"),  # GCP access tokens
    re.compile(r"(Bearer\s+[A-Za-z0-9_\-\.]{20,})"),  # Bearer tokens
    re.compile(r"(AKIA[A-Z0-9]{12,})"),  # AWS access keys
    re.compile(r"(-----BEGIN[A-Z ]*PRIVATE KEY-----)"),  # Private keys
]

FIX_DRIFT_PROMPT = """You are an expert Terraform engineer. Your task is to fix the Terraform code
so that `terraform plan` succeeds without errors and outputs:
"No changes. Your infrastructure matches the configuration."

CONTEXT:
- The code was auto-generated by reverse-engineering existing GCP infrastructure.
- The state file already contains the imported resources.
- You are fixing the CODE to match the REAL infrastructure, NOT changing the infrastructure.
- The plan output may show DRIFT (differences) or ERRORS (invalid HCL). Fix BOTH.

TWO TYPES OF ISSUES YOU MUST FIX:

TYPE 1 — TERRAFORM ERRORS (plan fails with Error):
These are HCL code issues. Common cases:
- "Unsupported block type" → rename the block (e.g. `rule` → `rules`, `access_config` → `access_config`)
- "Unsupported argument" → remove the argument or rename it to the correct one
- "Invalid resource type" → the resource type doesn't exist; check if it needs `google-beta` provider
- "Missing required argument" → add the missing argument with a sensible default
- "Invalid expression" → fix the HCL syntax
- "An argument named X is not expected here" → remove it or move it to the correct block

When fixing errors:
- Read the error message carefully — it tells you the exact file, line, and what's wrong.
- Apply the MINIMUM change to fix the error.
- Use your knowledge of the Google Terraform provider to determine correct argument names.
- For block type errors: the plural form is usually correct (e.g. `rules` not `rule`).

TYPE 2 — DRIFT (plan shows changes ~, +, -):
These are differences between code and real infrastructure state.
- If the plan shows an attribute CHANGING (~ lines), update to the "after" value.
- If the plan shows an attribute being REMOVED (- lines), remove it from the .tf code.
- If the plan shows an attribute being ADDED (+ lines), add it with the shown value.
- If a resource shows "# forces replacement", fix ONLY the specific parameter causing it.

STRICT RULES:
- Do NOT add `lifecycle {{ ignore_changes }}` blocks — ever.
- Do NOT add `depends_on` unless it was already there.
- Do NOT change resource names or types (unless the error specifically requires it).
- Do NOT add new resources or remove existing ones.
- Do NOT add comments, explanations, or annotations.
- Do NOT wrap output in markdown code fences.
- Preserve the original HCL formatting style (indentation, spacing, ordering).
- Keep all existing file markers (lines starting with "# ---") exactly as they are.

COMMON FIXES:
- `rule` → `rules` (google_compute_region_security_policy, google_compute_security_policy)
- `metadata_startup_script` vs `metadata.startup-script`: Use whichever the plan expects.
- `network_interface.access_config` empty block: Remove if plan says it shouldn't be there.
- `labels = {{}}` vs no labels block: Match exactly what the plan expects.
- Boolean values: Use `true`/`false` (not "true"/"false" strings).
- Numeric values: Don't quote them (use `3600` not `"3600"`).
- `project` field: Include it if the plan shows it's expected.
- If "Objects have changed outside of Terraform" appears, the code is correct — return unchanged.

Terraform Code:
```hcl
{tf_content}
```

Terraform Plan Output (last 4000 chars):
```
{plan_output}
```

Return ONLY the corrected Terraform code. No markdown fences. No explanations. No backticks wrapping."""


@dataclass
class DriftResult:
    """Result of a single drift check."""

    has_drift: bool
    plan_output: str
    resources_changed: int
    resources_added: int
    resources_destroyed: int


